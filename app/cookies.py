"""Netscape cookies.txt parsing plus browser/HTTP cookie helpers.

The user can attach their own cookies.txt for content they are allowed to
access with their own account. Cookies captured by Playwright are kept in
memory and serialised to a temporary Netscape file for yt-dlp.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

from .errors import InvalidCookies


@dataclass
class Cookie:
    domain: str
    path: str
    secure: bool
    expires: int
    name: str
    value: str
    http_only: bool = False


def parse_netscape_text(text: str) -> list[Cookie]:
    cookies: list[Cookie] = []
    for raw_line in text.splitlines():
        line = raw_line.strip("\r\n")
        if not line.strip():
            continue
        http_only = False
        if line.startswith("#HttpOnly_"):
            http_only = True
            line = line[len("#HttpOnly_") :]
        elif line.startswith("#"):
            continue

        parts = line.split("\t")
        if len(parts) < 7:
            continue
        domain, _flag, path, secure_raw, expiry_raw, name, value = parts[:7]
        value = "\t".join(parts[6:])
        if not domain or not name:
            continue
        try:
            expires = int(float(expiry_raw))
        except ValueError:
            expires = 0
        cookies.append(
            Cookie(
                domain=domain.strip(),
                path=path.strip() or "/",
                secure=secure_raw.strip().upper() == "TRUE",
                expires=expires,
                name=name.strip(),
                value=value,
                http_only=http_only,
            )
        )
    return cookies


def load_netscape_file(path: str | Path) -> list[Cookie]:
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        raise InvalidCookies("The cookies file could not be read.") from exc
    cookies = parse_netscape_text(text)
    if not cookies:
        raise InvalidCookies(
            "That does not look like a Netscape cookies.txt file.",
            hint="Export cookies with a browser extension in Netscape format, for a site and account you own.",
        )
    return cookies


def cookies_to_netscape(cookies: list[Cookie]) -> str:
    lines = ["# Netscape HTTP Cookie File", "# Generated by Universal Video Downloader", ""]
    for cookie in cookies:
        secure = "TRUE" if cookie.secure else "FALSE"
        expiry = str(max(0, cookie.expires))
        prefix = "#HttpOnly_" if cookie.http_only else ""
        lines.append(
            "\t".join(
                [
                    f"{prefix}{cookie.domain}",
                    "TRUE" if cookie.domain.startswith(".") else "FALSE",
                    cookie.path or "/",
                    secure,
                    expiry,
                    cookie.name,
                    cookie.value,
                ]
            )
        )
    return "\n".join(lines) + "\n"


def write_netscape_file(cookies: list[Cookie], path: str | Path) -> None:
    Path(path).write_text(cookies_to_netscape(cookies), encoding="utf-8")


def _domain_matches(host: str, domain: str) -> bool:
    domain = domain.lstrip(".").lower()
    return host == domain or host.endswith("." + domain)


def cookie_header_for(cookies: list[Cookie], url: str) -> str:
    try:
        parsed = urlsplit(url)
        host = (parsed.hostname or "").lower()
        path = parsed.path or "/"
        is_https = parsed.scheme.lower() == "https"
    except Exception:
        return ""
    now = time.time()
    selected: list[Cookie] = []
    for cookie in cookies:
        if not cookie.name or not _domain_matches(host, cookie.domain):
            continue
        if cookie.secure and not is_https:
            continue
        if cookie.expires and cookie.expires > 0 and cookie.expires < now:
            continue
        cookie_path = cookie.path or "/"
        if not path.startswith(cookie_path):
            continue
        selected.append(cookie)
    # Keep the most specific path last, like browsers do.
    selected.sort(key=lambda c: len(c.path or "/"))
    return "; ".join(f"{c.name}={c.value}" for c in selected)


def cookies_from_playwright(raw_cookies: list[dict]) -> list[Cookie]:
    cookies: list[Cookie] = []
    for item in raw_cookies:
        try:
            expires = int(item.get("expires") or 0)
        except (TypeError, ValueError):
            expires = 0
        cookies.append(
            Cookie(
                domain=str(item.get("domain") or ""),
                path=str(item.get("path") or "/"),
                secure=bool(item.get("secure")),
                expires=max(0, expires),
                name=str(item.get("name") or ""),
                value=str(item.get("value") or ""),
                http_only=bool(item.get("httpOnly")),
            )
        )
    return cookies


def cookies_for_playwright(cookies: list[Cookie]) -> list[dict]:
    payload: list[dict] = []
    for cookie in cookies:
        if not cookie.domain or not cookie.name:
            continue
        entry = {
            "name": cookie.name,
            "value": cookie.value,
            "domain": cookie.domain,
            "path": cookie.path or "/",
            "secure": cookie.secure,
            "httpOnly": cookie.http_only,
            "expires": cookie.expires if cookie.expires > 0 else -1,
        }
        payload.append(entry)
    return payload
